// 构建部编版数据结构（与苏教版同级：小学 → 年级 → 上册/下册；补充篇目单独一栏）
const buildBubianEdition = (): Edition => {
  const gradeNames = ["一年级", "二年级", "三年级", "四年级", "五年级", "六年级"];
  const gradeMap: { [key: string]: { 上册: Poetry[]; 下册: Poetry[] } } = {};
  gradeNames.forEach(name => { gradeMap[name] = { 上册: [], 下册: [] }; });

  bubianPoetryDataFull.forEach(poetry => {
    const id = poetry.id;
    if (id.startsWith("bb-buchong-")) {
      // 补充篇目不入年级，在下面单独处理
      return;
    }
    const parts = id.split("-");
    if (parts[0] !== "bb" || parts.length < 4) return;
    const gradeNum = parseInt(parts[1], 10);
    const semester = parts[2] === "1" ? "上册" : "下册";
    const gradeName = gradeNames[gradeNum - 1];
    if (gradeMap[gradeName]) {
      gradeMap[gradeName][semester].push(poetry);
    }
  });

  const buchongItems = bubianPoetryDataFull.filter(p => p.id.startsWith("bb-buchong-"));

  const grades: Grade[] = gradeNames.map(name => ({
    id: `bb-grade-${name}`,
    name,
    categories: [
      { id: `bb-${name}-上册`, name: "上册", items: gradeMap[name].上册 },
      { id: `bb-${name}-下册`, name: "下册", items: gradeMap[name].下册 },
    ],
  }));

  if (buchongItems.length > 0) {
    grades.push({
      id: "bb-grade-补充篇目",
      name: "补充篇目",
      categories: [{ id: "bb-补充篇目-篇目", name: "篇目", items: buchongItems }],
    });
  }

  return {
    id: "bubian",
    name: "部编版",
    description: "教育部统编教材",
    types: [
      {
        id: "poetry",
        name: "古诗词",
        icon: "📜",
        stages: [{ id: "primary", name: "小学", grades }],
      },
    ],
  };
};

