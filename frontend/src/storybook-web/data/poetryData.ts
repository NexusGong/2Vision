export interface Poetry {
  id: string;
  title: string;
  author: string;
  dynasty?: string;
  content: string[];
  fullText: string;
  tags?: string[]; // 标签：送别、思乡、边塞等
}

export interface Category {
  id: string;
  name: string;
  items: Poetry[];
}

export interface Grade {
  id: string;
  name: string;
  categories: Category[]; // 上册、下册 或其他分类
}

export interface Stage {
  id: string;
  name: string;
  grades: Grade[];
}

export interface ContentType {
  id: string;
  name: string;
  icon: string;
  stages: Stage[];
}

export interface Edition {
  id: string;
  name: string;
  description?: string;
  isCustom?: boolean;
  types: ContentType[];
}

